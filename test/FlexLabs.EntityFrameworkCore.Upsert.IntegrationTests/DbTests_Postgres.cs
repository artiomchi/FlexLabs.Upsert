#if !NOPOSTGRES
using System.Data.Common;
using FlexLabs.EntityFrameworkCore.Upsert.IntegrationTests.Base;
using FlexLabs.EntityFrameworkCore.Upsert.Tests.EF;
using Npgsql;
using Testcontainers.PostgreSql;
using Testcontainers.Xunit;
using Xunit.Sdk;

namespace FlexLabs.EntityFrameworkCore.Upsert.IntegrationTests;

public class DbTests_Postgres(DbTests_Postgres.DatabaseInitializer contexts) : DbTestsBase(contexts), IClassFixture<DbTests_Postgres.DatabaseInitializer>
{
    public sealed class DatabaseInitializer(IMessageSink messageSink) : ContainerisedDatabaseInitializerFixture<PostgreSqlBuilder, PostgreSqlContainer>(new PostgresFixture(messageSink))
    {
        public override DbDriver DbDriver => DbDriver.Postgres;

        protected override void ConfigureContextOptions(DbContextOptionsBuilder<TestDbContext> builder)
        {
            builder.UseNpgsql(new NpgsqlDataSourceBuilder(ConnectionString + ";Include Error Detail=true")
                .EnableDynamicJson()
                .Build());
        }

        private class PostgresFixture(IMessageSink messageSink) : DbContainerFixture<PostgreSqlBuilder, PostgreSqlContainer>(messageSink)
        {
            public override DbProviderFactory DbProviderFactory
                => NpgsqlFactory.Instance;

            // https://hub.docker.com/_/postgres/tags
            protected override PostgreSqlBuilder Configure()
                => ConfigureContainer(new PostgreSqlBuilder("postgres:18"));
        }
    }

    [Fact]
    public void GeneratedAlwaysAsIdentity_NoUpdate_New()
    {
        ResetDb();
        using var dbContext = new TestDbContext(_fixture.DataContextOptions);

        var newItem = new GeneratedAlwaysAsIdentity
        {
            Num1 = 1,
        };

        dbContext.GeneratedAlwaysAsIdentity.Upsert(newItem)
            .On(j => j.Num1)
            .NoUpdate()
            .Run();

        dbContext.GeneratedAlwaysAsIdentity.OrderBy(t => t.ID).Should().SatisfyRespectively(
            test => test.Should().MatchModel(new GeneratedAlwaysAsIdentity
            {
                Num1 = 1,
                Num2 = GeneratedAlwaysAsIdentity_NextId, // autogenerated
            }));
    }

    /// <summary>
    /// Postgres won't infer a partial index unless the command repeats its predicate, so before the
    /// predicate was emitted this failed outright with 42P10.
    /// </summary>
    [Fact]
    public void PartialUniqueIndex_Update_Matches()
    {
        ResetDb();
        SeedPartialIndexEntity(isDeleted: false);
        using var dbContext = new TestDbContext(_fixture.DataContextOptions);

        dbContext.TestEntitiesPartialIndex.Upsert(new TestEntityPartialIndex { Key = "key", Counter = 2 })
            .On(e => e.Key)
            .WhenMatched((e, en) => new TestEntityPartialIndex { Counter = en.Counter })
            .Run();

        dbContext.TestEntitiesPartialIndex.OrderBy(e => e.ID).Should().SatisfyRespectively(
            entity =>
            {
                entity.Key.Should().Be("key");
                entity.Counter.Should().Be(2);
            });
    }

    /// <summary>
    /// The rows the index excludes don't take part in the match, which is the whole reason to make
    /// an index partial - a soft deleted key stays reusable.
    /// </summary>
    [Fact]
    public void PartialUniqueIndex_Update_IgnoresRowsOutsideTheIndex()
    {
        ResetDb();
        SeedPartialIndexEntity(isDeleted: true);
        using var dbContext = new TestDbContext(_fixture.DataContextOptions);

        dbContext.TestEntitiesPartialIndex.Upsert(new TestEntityPartialIndex { Key = "key", Counter = 2 })
            .On(e => e.Key)
            .WhenMatched((e, en) => new TestEntityPartialIndex { Counter = en.Counter })
            .Run();

        dbContext.TestEntitiesPartialIndex.OrderBy(e => e.ID).Should().SatisfyRespectively(
            deleted =>
            {
                deleted.Counter.Should().Be(1);
                deleted.IsDeleted.Should().BeTrue();
            },
            inserted =>
            {
                inserted.Counter.Should().Be(2);
                inserted.IsDeleted.Should().BeFalse();
            });
    }

    private void SeedPartialIndexEntity(bool isDeleted)
    {
        using var dbContext = new TestDbContext(_fixture.DataContextOptions);
        dbContext.TestEntitiesPartialIndex.Add(new TestEntityPartialIndex
        {
            Key = "key",
            Counter = 1,
            IsDeleted = isDeleted,
        });
        dbContext.SaveChanges();
    }
}
